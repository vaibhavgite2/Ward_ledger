def main():
    base = sys.argv[1] if len(sys.argv) > 1 else "messages"
    os.makedirs(base, exist_ok=True)
    out = {"en": {}, "mr": {}, "hi": {}}
    for k, (e, m, h) in M.items():
        out["en"][k], out["mr"][k], out["hi"][k] = e, m, h
    for lang, d in out.items():
        with open(os.path.join(base, f"{lang}.json"), "w", encoding="utf-8") as f:
            json.dump(d, f, ensure_ascii=False, indent=1)
    for lang in out:
        p = os.path.join(base, f"officer.{lang}.json")
        if not os.path.exists(p):
            with open(p, "w", encoding="utf-8") as f:
                f.write("{}\n")
    print(len(M), "keys written to", base)


if __name__ == "__main__":
    main()
